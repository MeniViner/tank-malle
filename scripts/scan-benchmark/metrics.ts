/**
 * Scan benchmark metrics. Pure: session outcomes in, report numbers out.
 *
 * The unit of evaluation is a capture session (one physical display, one
 * attempt), never a frame: repeated frames of one session are not independent
 * trials. Intervals are Wilson score intervals over sessions, plus a
 * percentile bootstrap that resamples whole groups (one vehicle/pump) so a
 * display photographed many times cannot narrow the interval by itself.
 */
export type Kind = 'pump' | 'odometer';
export type Values = Record<string, string>;
export type SessionOutcome = {
  id: string; kind: Kind; group: string; family: string; device: string; split: string;
  /** Labelled as readable by a person, and as having one unambiguous answer. */
  eligible: boolean;
  expected: Values | null;
  status: 'accepted' | 'abstained';
  values?: Values; reason?: string; reasons?: Record<string, number>;
  latencyMs: number; frames: number;
};
export type Interval = { estimate: number | null; low: number | null; high: number | null; k: number; n: number };

export function wilson(k: number, n: number, z = 1.959964): Interval {
  if (!n) return { estimate: null, low: null, high: null, k, n };
  const p = k / n, denominator = 1 + z * z / n, centre = (p + z * z / (2 * n)) / denominator;
  const half = z * Math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denominator;
  return { estimate: p, low: Math.max(0, centre - half), high: Math.min(1, centre + half), k, n };
}
export function percentile(values: number[], p: number) {
  if (!values.length) return null;
  const sorted = [...values].sort((a, b) => a - b), rank = (sorted.length - 1) * p, low = Math.floor(rank);
  return sorted[low] + (sorted[Math.min(sorted.length - 1, low + 1)] - sorted[low]) * (rank - low);
}
/** Deterministic, so a report can be regenerated byte for byte. */
function random(seed: number) { return () => ((seed = Math.imul(seed ^ (seed >>> 15), 1 | seed) + 0x6d2b79f5 | 0) >>> 0) / 4294967296; }
export function groupBootstrap<T>(rows: T[], group: (row: T) => string, numerator: (row: T) => boolean, denominator: (row: T) => boolean, rounds = 2000, seed = 20261031) {
  const groups = [...rows.reduce((map, row) => map.set(group(row), [...(map.get(group(row)) ?? []), row]), new Map<string, T[]>()).values()];
  if (!groups.length) return { low: null, high: null, groups: 0 };
  const next = random(seed), estimates: number[] = [];
  for (let round = 0; round < rounds; round++) {
    let k = 0, n = 0;
    for (let i = 0; i < groups.length; i++) for (const row of groups[Math.floor(next() * groups.length)]) if (denominator(row)) { n++; if (numerator(row)) k++; }
    if (n) estimates.push(k / n);
  }
  return { low: percentile(estimates, .025), high: percentile(estimates, .975), groups: groups.length };
}

const REQUIRED: Record<Kind, string[]> = { pump: ['total', 'liters'], odometer: ['odometer'] };
/** Exact equality of the displayed number. "000850" and "850" are the same
 * odometer reading; "202.73" and "202.730" the same amount. Nothing else is. */
export function sameValue(field: string, a: string | undefined, b: string | undefined) {
  if (a === undefined || b === undefined) return false;
  if (field === 'odometer') return /^\d+$/.test(a) && /^\d+$/.test(b) && BigInt(a) === BigInt(b);
  return /^\d+(\.\d+)?$/.test(a) && /^\d+(\.\d+)?$/.test(b) && Number(a) === Number(b);
}
export function sessionCorrect(row: SessionOutcome) {
  return row.status === 'accepted' && !!row.expected && REQUIRED[row.kind].every(field => sameValue(field, row.values?.[field], row.expected?.[field]));
}

export function summarize(rows: SessionOutcome[]) {
  const accepted = rows.filter(r => r.status === 'accepted'), eligible = rows.filter(r => r.eligible);
  const correct = (r: SessionOutcome) => sessionCorrect(r);
  // A session with no single correct answer (unreadable, ambiguous, negative)
  // has any acceptance counted as wrong.
  const wrong = (r: SessionOutcome) => r.status === 'accepted' && !correct(r);
  const fields: Record<string, { correct: Interval; acceptedPrecision: Interval }> = {};
  for (const field of [...new Set(rows.flatMap(r => REQUIRED[r.kind]))]) {
    const withField = rows.filter(r => REQUIRED[r.kind].includes(field)), eligibleField = withField.filter(r => r.eligible);
    const acceptedField = withField.filter(r => r.status === 'accepted');
    const ok = (r: SessionOutcome) => r.status === 'accepted' && sameValue(field, r.values?.[field], r.expected?.[field] ?? undefined);
    fields[field] = { correct: wilson(eligibleField.filter(ok).length, eligibleField.length), acceptedPrecision: wilson(acceptedField.filter(ok).length, acceptedField.length) };
  }
  const reasons: Record<string, number> = {};
  for (const r of rows) if (r.status === 'abstained') reasons[r.reason ?? 'unknown'] = (reasons[r.reason ?? 'unknown'] ?? 0) + 1;
  const frameReasons: Record<string, number> = {};
  for (const r of rows) for (const [reason, count] of Object.entries(r.reasons ?? {})) frameReasons[reason] = (frameReasons[reason] ?? 0) + count;
  const latency = rows.map(r => r.latencyMs);
  return {
    sessions: rows.length, eligibleSessions: eligible.length, groups: new Set(rows.map(r => r.group)).size, acceptedSessions: accepted.length,
    completeSessionCorrect: wilson(eligible.filter(correct).length, eligible.length),
    acceptedPrecision: wilson(accepted.filter(correct).length, accepted.length),
    acceptedPrecisionGroupBootstrap: groupBootstrap(rows, r => r.group, correct, r => r.status === 'accepted'),
    wrongAcceptanceAmongAll: wilson(rows.filter(wrong).length, rows.length),
    wrongAcceptanceAmongIneligible: wilson(rows.filter(r => !r.eligible && r.status === 'accepted').length, rows.filter(r => !r.eligible).length),
    coverageEligible: wilson(eligible.filter(correct).length, eligible.length),
    coverageEligibleGroupBootstrap: groupBootstrap(eligible, r => r.group, correct, () => true),
    coverageAll: wilson(rows.filter(correct).length, rows.length),
    fields, sessionReasons: reasons, frameReasons,
    latencyMs: { p50: percentile(latency, .5), p95: percentile(latency, .95), max: latency.length ? Math.max(...latency) : null },
  };
}
export function breakdown(rows: SessionOutcome[], key: (row: SessionOutcome) => string) {
  const keys = [...new Set(rows.map(key))].sort();
  return Object.fromEntries(keys.map(k => {
    const subset = rows.filter(r => key(r) === k), eligible = subset.filter(r => r.eligible), accepted = subset.filter(r => r.status === 'accepted');
    return [k, { sessions: subset.length, eligible: eligible.length, correctEligible: wilson(eligible.filter(sessionCorrect).length, eligible.length), acceptedPrecision: wilson(accepted.filter(sessionCorrect).length, accepted.length), wrongAccepted: accepted.filter(r => !sessionCorrect(r)).length }];
  }));
}
/** Target verdicts use the interval, not the point estimate: a target is met
 * only when the whole 95% interval clears it. */
export function verdict(interval: Interval, target: number, direction: 'at-least' | 'at-most' = 'at-least') {
  if (interval.n === 0 || interval.low === null || interval.high === null) return 'not-measured';
  if (direction === 'at-least') return interval.low >= target ? 'met' : interval.high < target ? 'not-met' : 'unproven';
  return interval.high <= target ? 'met' : interval.low > target ? 'not-met' : 'unproven';
}
